// Package dictgen derives the generated OpenCC dictionaries from their
// sources, mirroring the scripts in OpenCC's data/scripts directory.
package dictgen

import (
	"fmt"
	"io/fs"
	"strings"
	"testing/fstest"
	"unicode/utf8"

	gocc "github.com/go-ego/gocc"
	"github.com/go-ego/gocc/internal/dictfile"
)

const (
	reversePrefix = "# @reverse-prefer:"
	tofuPrefix    = "# @tofu-risk:"
)

// reversed lists the dictionaries produced by swapping keys and values.
var reversed = map[string]string{
	"TWVariantsRev.txt":            "TWVariants.txt",
	"HKVariantsRev.txt":            "HKVariants.txt",
	"JPShinjitaiCharactersRev.txt": "JPShinjitaiCharacters.txt",
	"SealCharactersRev.txt":        "SealCharacters.txt",
	"SealVariantsRev.txt":          "SealVariants.txt",
}

// Generate returns the generated dictionaries, by file name, from the
// source dictionaries in dicts and the t2s config in configs.
func Generate(configs, dicts fs.FS) (map[string][]byte, error) {
	out := make(map[string][]byte)
	for dst, src := range reversed {
		data, err := fs.ReadFile(dicts, src)
		if err != nil {
			return nil, err
		}
		entries, err := Reverse(data)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", src, err)
		}
		out[dst] = dictfile.Format(header(dst, "reversed "+src), entries)
	}

	ts, err := fs.ReadFile(dicts, "TSCharacters.txt")
	if err != nil {
		return nil, err
	}
	ext, err := ExtractTofuRisk(ts)
	if err != nil {
		return nil, fmt.Errorf("TSCharacters.txt: %w", err)
	}
	out["TSCharactersExt.txt"] = dictfile.Format(
		header("TSCharactersExt.txt", "@tofu-risk mappings of TSCharacters.txt"), ext)

	// t2s needs TSCharactersExt, which is generated above
	overlay := fstest.MapFS{"TSCharactersExt.txt": {Data: out["TSCharactersExt.txt"]}}
	for _, name := range []string{"CJK_Compatibility_Ideographs.txt", "TSPhrases.txt", "TSCharacters.txt"} {
		data, err := fs.ReadFile(dicts, name)
		if err != nil {
			return nil, err
		}
		overlay[name] = &fstest.MapFile{Data: data}
	}
	config, err := fs.ReadFile(configs, "t2s.json")
	if err != nil {
		return nil, err
	}
	t2s, err := gocc.NewFromConfig(config, overlay, gocc.WithTofuRisk())
	if err != nil {
		return nil, err
	}
	var inputs [][]byte
	for _, name := range []string{"HKPhrases.txt", "TWPhrases.txt"} {
		data, err := fs.ReadFile(dicts, name)
		if err != nil {
			return nil, err
		}
		inputs = append(inputs, data)
	}
	st, err := STPhrases(t2s, inputs...)
	if err != nil {
		return nil, err
	}
	const name = "STPhrases_GeneratedFromRegionalPhrases.txt"
	out[name] = dictfile.Format(header(name, "HKPhrases.txt, TWPhrases.txt keys via t2s.json"), st)
	return out, nil
}

func header(file, source string) []string {
	return []string{
		"Open Chinese Convert (OpenCC) Dictionary",
		"File: " + file,
		"Generated by gocc internal/cmd/gendict from " + source + ". DO NOT EDIT.",
		"License: Apache-2.0",
	}
}

// Reverse swaps keys and values. Values keep their order of appearance,
// except that "# @reverse-prefer: key [value]" moves value (default key)
// to the front of the reversed key.
func Reverse(data []byte) ([]dictfile.Entry, error) {
	entries, err := dictfile.Parse(data)
	if err != nil {
		return nil, err
	}
	var keys []string
	values := make(map[string][]string)
	for _, e := range entries {
		for _, v := range e.Values {
			if _, ok := values[v]; !ok {
				keys = append(keys, v)
			}
			values[v] = append(values[v], e.Key)
		}
	}

	// like common.py, the last preference of a key wins
	var prefKeys []string
	prefs := make(map[string]string)
	for _, line := range strings.Split(string(data), "\n") {
		rest, ok := strings.CutPrefix(strings.TrimSuffix(line, "\r"), reversePrefix)
		if !ok {
			continue
		}
		f := strings.Fields(rest)
		if len(f) != 1 && len(f) != 2 {
			return nil, fmt.Errorf("invalid reverse preference: %q", line)
		}
		if _, ok := prefs[f[0]]; !ok {
			prefKeys = append(prefKeys, f[0])
		}
		prefs[f[0]] = f[len(f)-1]
	}
	for _, key := range prefKeys {
		prefer := prefs[key]
		vs := values[key]
		i := indexOf(vs, prefer)
		if i < 0 {
			return nil, fmt.Errorf("reverse preference %s -> %s has no mapping", key, prefer)
		}
		copy(vs[1:i+1], vs[:i])
		vs[0] = prefer
	}

	out := make([]dictfile.Entry, len(keys))
	for i, k := range keys {
		out[i] = dictfile.Entry{Key: k, Values: values[k]}
	}
	return out, nil
}

func indexOf(s []string, v string) int {
	for i, x := range s {
		if x == v {
			return i
		}
	}
	return -1
}

// ExtractTofuRisk returns the mappings that follow "# @tofu-risk:" lines,
// without the identity value kept as the default candidate.
func ExtractTofuRisk(data []byte) ([]dictfile.Entry, error) {
	lines := strings.Split(string(data), "\n")
	var out []dictfile.Entry
	for i, line := range lines {
		if !strings.HasPrefix(line, tofuPrefix) {
			continue
		}
		if i+1 >= len(lines) {
			return nil, fmt.Errorf("line %d: missing mapping after %s", i+1, tofuPrefix)
		}
		next := strings.TrimSuffix(lines[i+1], "\r")
		key, rest, ok := strings.Cut(next, "\t")
		if !ok || key == "" || strings.HasPrefix(next, "#") {
			return nil, fmt.Errorf("line %d: expected mapping after %s", i+1, tofuPrefix)
		}
		values := strings.Fields(rest)
		if len(values) > 0 && values[0] == key {
			values = values[1:]
		}
		if len(values) == 0 {
			return nil, fmt.Errorf("line %d: expected extension mapping after %s", i+1, tofuPrefix)
		}
		out = append(out, dictfile.Entry{Key: key, Values: values})
	}
	return out, nil
}

// STPhrases maps the Simplified form (by t2s) of regional phrase keys back
// to the phrases, so Simplified input keeps their span before the regional
// conversion. Projections shorter than 3 runes are skipped; a projection
// shared by different phrases is an error.
func STPhrases(t2s *gocc.Converter, inputs ...[]byte) ([]dictfile.Entry, error) {
	var keys []string
	origin := make(map[string]string)
	for _, data := range inputs {
		entries, err := dictfile.Parse(data)
		if err != nil {
			return nil, err
		}
		for _, e := range entries {
			simp := t2s.Convert(e.Key)
			if utf8.RuneCountInString(simp) < 3 {
				continue
			}
			prev, ok := origin[simp]
			if !ok {
				keys = append(keys, simp)
				origin[simp] = e.Key
			} else if prev != e.Key {
				return nil, fmt.Errorf("conflicting regional phrases for %s: %s %s", simp, prev, e.Key)
			}
		}
	}
	out := make([]dictfile.Entry, len(keys))
	for i, k := range keys {
		out[i] = dictfile.Entry{Key: k, Values: []string{origin[k]}}
	}
	return out, nil
}
